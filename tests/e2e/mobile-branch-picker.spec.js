import { test, expect } from './fixtures'

test('quản lý chọn cơ sở bằng menu đồng bộ trên điện thoại', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('xuly.session', JSON.stringify({ token: 'manager-test', user: { id: 1, fullname: 'Quản lý', system_role: 'MANAGER' } })))
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    if (!path.startsWith('/api/')) return route.continue()
    if (path === '/api/branches') return route.fulfill({ json: { data: [{ id: 1, name: 'Cơ sở Một' }, { id: 2, name: 'Cơ sở Hai' }], total: 2 } })
    return route.fulfill({ json: { data: [], total: 0 } })
  })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/treatments')
  const trigger = page.getByRole('button', { name: 'Chọn chi nhánh' })
  await expect(trigger).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Chọn chi nhánh' })).toHaveCount(0)
  await trigger.click()
  const menu = page.locator('.branch-picker-options')
  await expect(menu.getByRole('button')).toHaveCount(3)
  await expect(menu).toBeInViewport()
  await menu.getByRole('button', { name: 'Cơ sở Hai' }).click()
  await expect(trigger).toContainText('Cơ sở Hai')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('xuly.branch'))).toBe('2')
  await page.reload()
  await expect(trigger).toContainText('Cơ sở Hai')
  await trigger.click()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await trigger.click()
  await menu.getByRole('button', { name: 'Tất cả chi nhánh' }).click()
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('xuly.branch'))).toBe('')
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(trigger).toBeVisible()
  await expect(page.locator('.branch-picker-label')).toBeVisible()
  await trigger.click()
  await expect(menu.getByRole('button')).toHaveCount(3)
  await menu.getByRole('button', { name: 'Cơ sở Một' }).click()
  await expect(trigger).toContainText('Cơ sở Một')
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('xuly.branch'))).toBe('1')
  await trigger.click()
  await page.mouse.click(30, 150)
  await expect(menu).toBeHidden()
})