const parent = { id: 20, name: 'Liệu trình trị nám', is_product: 0, price: 30000000, sale_price: 30000000, child_service_ids: [12, 15] }
const children = [{ id: 12, name: 'Laser trị nám', is_product: 0 }, { id: 15, name: 'Điện di', is_product: 0 }]
const retail = { id: 30, name: 'Serum', is_product: 1, price: 100000, child_service_ids: [] }
const standalone = { id: 40, name: 'pnp', is_product: 0, price: 1000000, child_service_ids: [] }

async function setup(page, { failChild = false, failSave = false, existing = false, executions = [], failExecute = false, standaloneProduct = standalone } = {}) {
  const requests = []
  await page.addInitScript(() => { sessionStorage.setItem('xuly.branch', '1'); localStorage.setItem('xuly.session', JSON.stringify({ token: 'test-token', user: { id: 1, branch_id: 1, fullname: 'Quản lý', system_role: 'MANAGER' } })) })
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    if (!path.startsWith('/api/')) return route.continue()
    if (path === '/api/branches') return route.fulfill({ json: { data: [{ id: 1, name: 'Cơ sở chính' }], total: 1 } })
    if (path === '/api/roles') return route.fulfill({ json: { data: [{ id: 4, name: 'Kỹ thuật viên' }, { id: 5, name: 'Bác sĩ' }], totalPages: 1, total: 2 } })
    if (path === '/api/staffs') return route.fulfill({ json: { data: [{ id: 2, fullname: 'Lan', role_id: 4, branch_id: 1 }, { id: 3, fullname: 'Mai', role_id: 5, branch_id: 1 }], totalPages: 1, total: 2 } })
    if (path === '/api/products') return route.fulfill({ json: { data: [parent, retail, standaloneProduct], total: 3 } })
    if (path.startsWith('/api/products/')) {
      if (failChild) return route.fulfill({ status: 500, json: { message: 'Lỗi tải dịch vụ' } })
      return route.fulfill({ json: { data: children.find(item => path.endsWith(`/${item.id}`)) } })
    }
    if (path === '/api/customers') return route.fulfill({ json: { data: [{ id: 10, fullname: 'Khách A', wallet_balance: 0 }], total: 1 } })
    if (path === '/api/customers/10') return route.fulfill({ json: { data: { id: 10, fullname: 'Khách A', wallet_balance: 0 } } })
    if (path === '/api/invoices' && route.request().method() === 'POST') {
      requests.push(route.request().postDataJSON())
      return route.fulfill(failSave ? { status: 400, json: { message: 'Cấu hình dịch vụ đã thay đổi.' } } : { json: { invoiceId: 88, itemMappings: requests.at(-1).items.map((_, index) => ({ request_index: index, treatment_id: 200 + index * 10, children: [{ id: 201 + index * 10, product_id: 12 }, { id: 202 + index * 10, product_id: 15 }] })) } })
    }
    if (path === '/api/treatments/201') return route.fulfill({ json: { data: { id: 201, product_id: 12, parent_treatment_id: 200, remaining_sessions: null, histories: [] } } })
    if (path === '/api/treatments/200') return route.fulfill({ json: { data: { id: 200, product_id: 40, remaining_sessions: null, histories: [] } } })
    if (path === '/api/treatments/execute') { executions.push(route.request().postDataJSON()); return route.fulfill(failExecute ? { status: 500, json: { message: 'Lỗi ghi nhận buổi' } } : { json: { treatmentHistoryId: 500 } }) }
    if (path === '/api/invoices/88') return route.fulfill({ json: { data: { id: 88, customer_id: 10, customer_name: 'Khách A', items: [{ product_id: 20, snapshot_name: parent.name, snapshot_price: 40000000, quantity: 1, treatment: { id: 200, total_sessions: null, children: [{ id: 201, product_name: 'Laser đã mua', total_sessions: 5 }, { id: 202, product_name: 'Điện di đã mua', total_sessions: null }] } }] } } })
    if (path === '/api/invoices') return route.fulfill({ json: { data: existing ? [{ id: 88, customer_name: 'Khách A', total_amount: 40000000 }] : [], total: existing ? 1 : 0 } })
    return route.fulfill({ json: { data: [], total: 0 } })
  })
  await page.goto('/invoices')
  return requests
}

async function addPackage(page, pending = true) {
  await page.getByRole('button', { name: /Thêm sản phẩm\s*\/\s*dịch vụ/ }).click()
  const line = page.locator('.compact-invoice-line').nth(await page.locator('.compact-invoice-line').count() - 1)
  await line.getByRole('combobox', { name: 'Tìm sản phẩm / dịch vụ' }).click()
  await page.getByRole('option', { name: parent.name }).click()
  if (pending) {
    await line.getByRole('checkbox', { name: 'Chưa làm Laser trị nám' }).check()
    await line.getByRole('checkbox', { name: 'Chưa làm Điện di' }).check()
  }
  return line
}

